// `pnpm contract:build` (P3-02): writes contracts/openapi.yaml (OpenAPI 3.1) from the contract registry
// (src/contracts/registry.ts, ADR-0002 §Decision 1). One operation per registry entry: method + path + operationId, the
// request (query for GET/DELETE, JSON body otherwise), the 200 response and the shared ApiError body for 4XX/5XX. The
// summary is the H1 of the contract file (docs/requirements/view-data-contracts/<ID>-*.md), e.g. "C-01 — Create
// analysis draft"; the description names that file.
// The output depends only on the registry (entries sorted by id, no timestamps), so a rebuild of an unchanged registry
// is byte-identical; the acceptance check and CI rebuild it and fail on any diff.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  OpenAPIRegistry,
  OpenApiGeneratorV31,
  extendZodWithOpenApi,
} from '@asteasolutions/zod-to-openapi';
import { stringify } from 'yaml';
import { z } from 'zod';

import type { RouteConfig } from '@asteasolutions/zod-to-openapi';

/** SemVer of the published contract (info.version). Bump it with every contract change: major on a breaking one. */
export const CONTRACT_VERSION = '0.2.0';

// Adds `.openapi()` to the Zod prototype; the registry names components through it (registry.register). Zod v4 copies
// prototype methods onto each schema when it is created, so the contract modules are imported only after this call.
extendZodWithOpenApi(z);
const { ApiErrorSchema } = await import('../../src/contracts/common/api-error.js');
const { CONTRACT_SCHEMAS } = await import('../../src/contracts/registry.js');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outFile = join(root, 'contracts', 'openapi.yaml');
const HEADER =
  '# Generated by `pnpm contract:build` (tools/contract/build-openapi.ts) — do not edit by hand.\n';

const contractsDir = join(root, 'docs', 'requirements', 'view-data-contracts');

/** Contract id ("C-01", the first two "-" parts of the file name) → its file name and H1 title without "# ". */
function contractTitles(): Map<string, { file: string; title: string }> {
  const titles = new Map<string, { file: string; title: string }>();
  for (const file of readdirSync(contractsDir).sort()) {
    if (!file.endsWith('.md')) continue;
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- a file listed from that folder.
    const h1 = readFileSync(join(contractsDir, file), 'utf8')
      .split(/\r?\n/)
      .find((line) => line.startsWith('# '));
    if (h1 === undefined) throw new Error(`${file} has no "# " title`);
    titles.set(file.split('-').slice(0, 2).join('-'), { file, title: h1.slice(2).trim() });
  }
  return titles;
}

const titles = contractTitles();

/** Component name of a contract id: "V-03" → "V03". */
const componentName = (id: string): string => id.replace(/-/g, '');

/** Express `:param` → OpenAPI `{param}`, plus the names of the path parameters. */
function openApiPath(path: string): { path: string; params: string[] } {
  const params: string[] = [];
  const converted = path.replace(/:([A-Za-z_]\w*)/g, (_match, name: string) => {
    params.push(name);
    return `{${name}}`;
  });
  return { path: converted, params };
}

const registry = new OpenAPIRegistry();
// zod-to-openapi 9.1.0 recurses forever on the recursive `z.json()` of `details`; the spec states the same thing, any
// JSON value, as an unconstrained schema. Only the OpenAPI copy changes: the runtime contract keeps `z.json()`.
const apiError = registry.register(
  'ApiError',
  ApiErrorSchema.extend({
    details: z.unknown().optional().openapi({
      description: 'Optional diagnostic data: any JSON value. The UI never shows it verbatim.',
    }),
  }),
);
const errorContent = { 'application/json': { schema: apiError } };

for (const [id, entry] of Object.entries(CONTRACT_SCHEMAS).sort(([a], [b]) => a.localeCompare(b))) {
  const name = componentName(id);
  const contract = titles.get(id);
  if (!contract)
    throw new Error(`${id}: no contract file in docs/requirements/view-data-contracts/`);
  const { path, params } = openApiPath(entry.endpoint.path);
  const method = entry.endpoint.method.toLowerCase() as RouteConfig['method'];
  const request: NonNullable<RouteConfig['request']> = {};
  if (params.length > 0) {
    request.params = z.object(Object.fromEntries(params.map((param) => [param, z.string()])));
  }
  if (entry.request) {
    const schema = registry.register(`${name}Request`, entry.request);
    if (method === 'get' || method === 'delete') {
      if (!(schema instanceof z.ZodObject)) {
        throw new Error(
          `${id}: a ${entry.endpoint.method} request must be a z.object (query parameters)`,
        );
      }
      request.query = schema;
    } else {
      request.body = { required: true, content: { 'application/json': { schema } } };
    }
  }
  registry.registerPath({
    method,
    path,
    operationId: entry.operationId,
    summary: contract.title,
    description: `Contract ${id}: docs/requirements/view-data-contracts/${contract.file}`,
    tags: [id],
    ...(Object.keys(request).length > 0 ? { request } : {}),
    responses: {
      200: {
        description: `${id} response`,
        content: {
          'application/json': {
            // O-03's JSON body is the ApiError itself (CF-118): reuse the component, whose `details` avoids the
            // recursive z.json() the generator cannot walk.
            schema:
              entry.response === ApiErrorSchema
                ? apiError
                : registry.register(`${name}Response`, entry.response),
          },
        },
      },
      '4XX': { description: 'Client error (ApiError body)', content: errorContent },
      '5XX': { description: 'Server error (ApiError body)', content: errorContent },
    },
  });
}

const document = new OpenApiGeneratorV31(registry.definitions).generateDocument({
  openapi: '3.1.0',
  info: {
    title: 'eco-comparator-bff',
    version: CONTRACT_VERSION,
    description:
      'HTTP contract of the Eco-Comparador BFF, generated from the Zod registry (src/contracts/registry.ts).',
  },
});

writeFileSync(outFile, HEADER + stringify(document, { lineWidth: 0 }));
process.stdout.write(
  `wrote ${String(Object.keys(document.paths ?? {}).length)} path(s) to contracts/openapi.yaml (OpenAPI ${document.openapi})\n`,
);
